"""Reachable-workspace banks: verified-feasible TCP targets with a joint solution each.

A target is *feasible* when some arm configuration
  * lies inside the 90 % soft joint limits (wrist_roll and gripper at their fixed values),
  * puts the TCP at that point with the TCP at least ``min_tcp_z`` above the table,
  * keeps every collision geom at least ``clearance`` away from the floor, the base and
    the rest of the arm (no self-collision),
  * faces its target: the TCP lies at least ``min_forward_reach`` in front of the pan axis
    along the pan direction. This excludes "folded-back" configurations in which the arm
    reaches over the top of its own base (19 % of collision-free joint space); they are
    kinematically valid but unsafe and irrelevant for tabletop manipulation.

Banks are generated by uniform joint-space sampling + CPU MuJoCo FK/collision checks and
then voxel-balanced (at most ``per_voxel`` points per ``voxel`` cube) so that sampling a
bank entry uniformly is approximately uniform over the reachable *volume*, not biased
toward regions where many joint configurations map.

Train and evaluation banks are generated from independent seeds and stored separately
(``data/workspace/{train,eval}.npz``); evaluation targets are never drawn from the train
bank.
"""

from __future__ import annotations

import multiprocessing as mp
from dataclasses import asdict, dataclass
from pathlib import Path

import mujoco
import numpy as np

from so101_reach.sim import so101

WORKSPACE_DIR: Path = so101.PROJECT_ROOT / "data" / "workspace"


@dataclass(frozen=True)
class WorkspaceSpec:
  num_samples: int = 3_000_000
  seed: int = 0
  clearance: float = 0.004
  min_tcp_z: float = 0.02
  voxel: float = 0.01
  per_voxel: int = 4
  min_forward_reach: float | None = 0.02


@dataclass
class WorkspaceBank:
  joint_pos: np.ndarray  # (N, 4) arm joint angles [rad], order so101.ARM_JOINTS.
  tcp_pos: np.ndarray  # (N, 3) TCP position in the base frame [m].
  spec: WorkspaceSpec

  def save(self, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
      path, joint_pos=self.joint_pos, tcp_pos=self.tcp_pos, **{f"spec_{k}": v for k, v in asdict(self.spec).items()}
    )

  @staticmethod
  def load(path: Path) -> WorkspaceBank:
    d = np.load(path)
    spec = WorkspaceSpec(**{k[5:]: d[k].item() for k in d.files if k.startswith("spec_")})
    return WorkspaceBank(d["joint_pos"].astype(np.float32), d["tcp_pos"].astype(np.float32), spec)

  def __len__(self) -> int:
    return len(self.tcp_pos)


def soft_joint_limits(model: mujoco.MjModel) -> np.ndarray:
  lim = np.array([model.jnt_range[model.joint(n).id] for n in so101.ARM_JOINTS])
  mid, half = lim.mean(1), (lim[:, 1] - lim[:, 0]) / 2
  half = half * so101.SOFT_JOINT_LIMIT_FACTOR
  return np.stack([mid - half, mid + half], axis=1)


_WORKER: dict = {}


def _init_worker(clearance: float) -> None:
  model = so101.make_cpu_model()
  # Contacts are generated (and reported with their signed distance) within `margin`.
  coll = (model.geom_contype > 0) | (model.geom_conaffinity > 0)
  model.geom_margin[coll] = clearance
  model.geom_gap[coll] = 0.0
  _WORKER["model"] = model
  _WORKER["data"] = mujoco.MjData(model)
  _WORKER["qadr"] = np.array([model.jnt_qposadr[model.joint(n).id] for n in so101.ALL_JOINTS])
  _WORKER["site"] = model.site(so101.TCP_SITE).id
  _WORKER["fixed"] = np.array([so101.FIXED_JOINT_TARGETS[n] for n in so101.FIXED_JOINTS])
  _WORKER["clearance"] = clearance


def _check_chunk(q_chunk: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
  model, data = _WORKER["model"], _WORKER["data"]
  qadr, site, fixed, clearance = _WORKER["qadr"], _WORKER["site"], _WORKER["fixed"], _WORKER["clearance"]
  ok = np.zeros(len(q_chunk), dtype=bool)
  tcp = np.zeros((len(q_chunk), 3), dtype=np.float32)
  for i, q in enumerate(q_chunk):
    data.qpos[qadr[:4]] = q
    data.qpos[qadr[4:]] = fixed
    mujoco.mj_kinematics(model, data)
    mujoco.mj_collision(model, data)
    tcp[i] = data.site_xpos[site]
    ok[i] = data.ncon == 0 or bool(np.all(data.contact.dist[: data.ncon] >= clearance))
  return ok, tcp


def check_configs(q: np.ndarray, clearance: float, workers: int | None = None) -> tuple[np.ndarray, np.ndarray]:
  """Return (collision_free_mask, tcp_positions) for arm configs q (N, 4)."""
  workers = workers or max(1, mp.cpu_count() - 2)
  chunks = np.array_split(q, max(1, len(q) // 20_000))
  with mp.get_context("spawn").Pool(workers, initializer=_init_worker, initargs=(clearance,)) as pool:
    res = pool.map(_check_chunk, chunks)
  return np.concatenate([r[0] for r in res]), np.concatenate([r[1] for r in res])


def forward_reach(model: mujoco.MjModel, q: np.ndarray, tcp: np.ndarray) -> np.ndarray:
  """Horizontal distance of the TCP in front of the pan axis, along the pan direction [m]."""
  data = mujoco.MjData(model)
  mujoco.mj_kinematics(model, data)
  jid = model.joint("shoulder_pan").id
  anchor = data.xanchor[jid][:2]
  s = np.sign(data.xaxis[jid][2])
  u = np.stack([np.cos(s * q[:, 0]), np.sin(s * q[:, 0])], axis=1)
  return ((tcp[:, :2] - anchor) * u).sum(axis=1)


def voxel_balance(tcp: np.ndarray, voxel: float, per_voxel: int, rng: np.random.Generator) -> np.ndarray:
  """Indices keeping at most `per_voxel` random points per voxel."""
  keys = np.floor(tcp / voxel).astype(np.int64)
  order = rng.permutation(len(tcp))
  _, inv = np.unique(keys[order], axis=0, return_inverse=True)
  inv = inv.reshape(-1)
  # Rank of each point within its voxel (in random order).
  sort = np.argsort(inv, kind="stable")
  counts = np.bincount(inv)
  starts = np.concatenate([[0], np.cumsum(counts)[:-1]])
  rank = np.empty_like(inv)
  rank[sort] = np.arange(len(inv)) - np.repeat(starts, counts)
  return order[rank < per_voxel]


def build_bank(spec: WorkspaceSpec, workers: int | None = None) -> WorkspaceBank:
  model = so101.make_cpu_model()
  lim = soft_joint_limits(model)
  rng = np.random.default_rng(spec.seed)
  q = rng.uniform(lim[:, 0], lim[:, 1], size=(spec.num_samples, 4)).astype(np.float64)
  ok, tcp = check_configs(q, spec.clearance, workers)
  ok &= tcp[:, 2] >= spec.min_tcp_z
  if spec.min_forward_reach is not None:
    ok &= forward_reach(model, q, tcp) >= spec.min_forward_reach
  q, tcp = q[ok], tcp[ok]
  keep = voxel_balance(tcp, spec.voxel, spec.per_voxel, rng)
  return WorkspaceBank(q[keep].astype(np.float32), tcp[keep].astype(np.float32), spec)


def bank_path(split: str) -> Path:
  return WORKSPACE_DIR / f"{split}.npz"


def load_bank(split: str) -> WorkspaceBank:
  path = bank_path(split)
  if not path.exists():
    raise FileNotFoundError(f"{path} missing. Run: python scripts/build_workspace.py")
  return WorkspaceBank.load(path)
